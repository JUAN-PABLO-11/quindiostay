-- ---------------------------------------------------------------------
-- Vista: estado de pago de cada reserva.
-- Una reserva está pagada solo cuando sus pagos exitosos cubren su valor total.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_pago_reserva AS
SELECT r.id_reserva,
       r.id_cliente,
       r.estado,
       r.valor_total,
       NVL(SUM(CASE WHEN p.estado_pago = 'exitoso' THEN p.monto END), 0)                 AS pagado,
       r.valor_total - NVL(SUM(CASE WHEN p.estado_pago = 'exitoso' THEN p.monto END), 0) AS saldo,
       CASE WHEN NVL(SUM(CASE WHEN p.estado_pago = 'exitoso' THEN p.monto END), 0) >= r.valor_total
            THEN 'si' ELSE 'no' END                                                     AS pagada
  FROM reserva r
  LEFT JOIN pago p ON p.id_reserva = r.id_reserva
 GROUP BY r.id_reserva, r.id_cliente, r.estado, r.valor_total;

COMMENT ON TABLE v_pago_reserva IS 'Lo pagado, el saldo y si la reserva está pagada';


