-- =====================================================================
-- QuindioStay - 01_ddl.sql
-- Tablas, claves primarias, foráneas, únicas y CHECK (23 tablas:
-- 18 fuertes, 2 débiles, 1 subtipo y 2 tablas puente N:M).

-- Correr conectado como QUINDIOSTAY, después de 00_reset.sql.

-- Convenciones:
--   * Identificadores con IDENTITY (Oracle genera el número). Se pueden
--     insertar valores explícitos en los datos de prueba.
--   * Valores de dominio en minúscula y sin tildes ('publico', 'basico',
--     'tarjeta de credito'...) para evitar problemas de codificación.
--   * Nombres de restricciones: pk_ / fk_ / uq_ / ck_ + tabla + campo,
--     para que el mensaje de error de Oracle diga qué falló.
--   * En Oracle no existe ON DELETE RESTRICT: una FK sin ON DELETE ya
--     impide borrar al padre si tiene hijos (equivale a RESTRICT).
--   * Reglas que miran otras tablas o la fecha actual (SYSDATE no se
--     permite en CHECK) van en 02_triggers.sql y en la capa de lógica.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Catálogos
-- ---------------------------------------------------------------------

CREATE TABLE municipio (
    id_municipio  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    codigo_dane   CHAR(5)       NOT NULL,
    nombre        VARCHAR2(30)  NOT NULL,
    CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
    CONSTRAINT uq_municipio_dane   UNIQUE (codigo_dane),
    CONSTRAINT uq_municipio_nombre UNIQUE (nombre),
    CONSTRAINT ck_municipio_dane   CHECK (REGEXP_LIKE(codigo_dane, '^[0-9]{5}$'))
);

CREATE TABLE tipo_prestador (
    id_tipo_prestador NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_tipo_prestador        PRIMARY KEY (id_tipo_prestador),
    CONSTRAINT uq_tipo_prestador_nombre UNIQUE (nombre)
);

CREATE TABLE rol (
    id_rol  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre  VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_rol        PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE tipo_componente (
    id_tipo_componente NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(15) NOT NULL,
    CONSTRAINT pk_tipo_componente        PRIMARY KEY (id_tipo_componente),
    CONSTRAINT uq_tipo_componente_nombre UNIQUE (nombre)
);


-- ---------------------------------------------------------------------
-- Prestadores y usuarios del sistema
-- ---------------------------------------------------------------------

CREATE TABLE prestador (
    id_prestador      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre_comercial  VARCHAR2(100) NOT NULL,
    nit               VARCHAR2(15)  NOT NULL,
    numero_rnt        VARCHAR2(10)  NOT NULL,
    direccion         VARCHAR2(120) NOT NULL,
    telefono          VARCHAR2(10)  NOT NULL,
    correo            VARCHAR2(100) NOT NULL,
    estado            VARCHAR2(10)  DEFAULT 'activo' NOT NULL,
    id_tipo_prestador NUMBER(10)    NOT NULL,
    id_municipio      NUMBER(10)    NOT NULL,
    CONSTRAINT pk_prestador          PRIMARY KEY (id_prestador),
    CONSTRAINT uq_prestador_nit      UNIQUE (nit),
    CONSTRAINT uq_prestador_rnt      UNIQUE (numero_rnt),
    CONSTRAINT ck_prestador_nit      CHECK (REGEXP_LIKE(nit, '^[0-9-]{6,15}$')),
    CONSTRAINT ck_prestador_rnt      CHECK (REGEXP_LIKE(numero_rnt, '^[0-9]{1,10}$')),
    CONSTRAINT ck_prestador_telefono CHECK (REGEXP_LIKE(telefono, '^(3[0-9]{9}|60[1-8][0-9]{7})$')),
    CONSTRAINT ck_prestador_correo   CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
    CONSTRAINT ck_prestador_estado   CHECK (estado IN ('activo', 'suspendido', 'retirado')),
    CONSTRAINT fk_prestador_tipo      FOREIGN KEY (id_tipo_prestador) REFERENCES tipo_prestador (id_tipo_prestador),
    CONSTRAINT fk_prestador_municipio FOREIGN KEY (id_municipio)      REFERENCES municipio (id_municipio)
);

CREATE TABLE usuario_sistema (
    id_usuario         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre_usuario     VARCHAR2(30) NOT NULL,
    contrasena_cifrada VARCHAR2(60) NOT NULL,
    estado             VARCHAR2(10) DEFAULT 'activo' NOT NULL,
    id_rol             NUMBER(10)   NOT NULL,
    id_prestador       NUMBER(10),              -- solo para el rol "encargado de prestador" (RN03, trigger)
    CONSTRAINT pk_usuario_sistema     PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_nombre      UNIQUE (nombre_usuario),
    CONSTRAINT ck_usuario_nombre      CHECK (REGEXP_LIKE(nombre_usuario, '^[^ ]{4,30}$')),
    CONSTRAINT ck_usuario_contrasena  CHECK (LENGTH(contrasena_cifrada) = 60),
    CONSTRAINT ck_usuario_estado      CHECK (estado IN ('activo', 'bloqueado')),
    CONSTRAINT fk_usuario_rol         FOREIGN KEY (id_rol)       REFERENCES rol (id_rol),
    CONSTRAINT fk_usuario_prestador   FOREIGN KEY (id_prestador) REFERENCES prestador (id_prestador) ON DELETE SET NULL
);


-- ---------------------------------------------------------------------
-- Oferta turística: destinos, paquetes, planes, componentes y salidas
-- ---------------------------------------------------------------------

CREATE TABLE destino (
    id_destino   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR2(80)  NOT NULL,
    descripcion  VARCHAR2(500),
    id_municipio NUMBER(10)    NOT NULL,
    CONSTRAINT pk_destino           PRIMARY KEY (id_destino),
    CONSTRAINT fk_destino_municipio FOREIGN KEY (id_municipio) REFERENCES municipio (id_municipio)
);

CREATE TABLE paquete (
    id_paquete      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(100)  NOT NULL,
    descripcion     VARCHAR2(1000) NOT NULL,
    duracion_dias   NUMBER(2)      NOT NULL,
    categoria       VARCHAR2(15)   NOT NULL,
    minimo_viajeros NUMBER(2)      NOT NULL,
    visibilidad     VARCHAR2(10)   DEFAULT 'publico' NOT NULL,
    id_destino      NUMBER(10)     NOT NULL,
    id_prestador    NUMBER(10)     NOT NULL,
    CONSTRAINT pk_paquete             PRIMARY KEY (id_paquete),
    CONSTRAINT ck_paquete_duracion    CHECK (duracion_dias BETWEEN 1 AND 30),
    CONSTRAINT ck_paquete_categoria   CHECK (categoria IN ('cultural', 'cafetero', 'aventura', 'naturaleza', 'familiar')),
    CONSTRAINT ck_paquete_minimo      CHECK (minimo_viajeros BETWEEN 1 AND 50),
    CONSTRAINT ck_paquete_visibilidad CHECK (visibilidad IN ('publico', 'privado')),
    CONSTRAINT fk_paquete_destino     FOREIGN KEY (id_destino)   REFERENCES destino (id_destino),
    CONSTRAINT fk_paquete_prestador   FOREIGN KEY (id_prestador) REFERENCES prestador (id_prestador)
);

-- Entidad débil de PAQUETE (relación identificadora "detalla")
CREATE TABLE itinerario_dia (
    id_paquete  NUMBER(10)    NOT NULL,
    numero_dia  NUMBER(2)     NOT NULL,
    descripcion VARCHAR2(500) NOT NULL,
    CONSTRAINT pk_itinerario_dia     PRIMARY KEY (id_paquete, numero_dia),
    CONSTRAINT ck_itinerario_numero  CHECK (numero_dia >= 1),  -- tope = duracion_dias (RN11, trigger)
    CONSTRAINT fk_itinerario_paquete FOREIGN KEY (id_paquete) REFERENCES paquete (id_paquete) ON DELETE CASCADE
);

CREATE TABLE plan (
    id_plan               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR2(80)   NOT NULL,
    descripcion           VARCHAR2(1000) NOT NULL,
    tipo_plan             VARCHAR2(15)   NOT NULL,
    precio                NUMBER(10)     NOT NULL,
    fecha_inicio_vigencia DATE           NOT NULL,
    fecha_fin_vigencia    DATE           NOT NULL,
    estado                VARCHAR2(10)   DEFAULT 'activo' NOT NULL,
    id_paquete            NUMBER(10)     NOT NULL,
    CONSTRAINT pk_plan                PRIMARY KEY (id_plan),
    CONSTRAINT uq_plan_paquete_nombre UNIQUE (id_paquete, nombre),          -- RN09
    CONSTRAINT ck_plan_tipo           CHECK (tipo_plan IN ('basico', 'estandar', 'premium', 'todo incluido')),
    CONSTRAINT ck_plan_precio         CHECK (precio > 0 AND precio <= 50000000),
    CONSTRAINT ck_plan_vigencia       CHECK (fecha_fin_vigencia >= fecha_inicio_vigencia),
    CONSTRAINT ck_plan_estado         CHECK (estado IN ('activo', 'inactivo')),
    CONSTRAINT fk_plan_paquete        FOREIGN KEY (id_paquete) REFERENCES paquete (id_paquete)
);

CREATE TABLE componente (
    id_componente      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR2(100) NOT NULL,
    descripcion        VARCHAR2(500),
    costo              NUMBER(10)    NOT NULL,
    id_tipo_componente NUMBER(10)    NOT NULL,
    id_prestador       NUMBER(10)    NOT NULL,
    CONSTRAINT pk_componente           PRIMARY KEY (id_componente),
    CONSTRAINT ck_componente_costo     CHECK (costo > 0),
    CONSTRAINT fk_componente_tipo      FOREIGN KEY (id_tipo_componente) REFERENCES tipo_componente (id_tipo_componente),
    CONSTRAINT fk_componente_prestador FOREIGN KEY (id_prestador)       REFERENCES prestador (id_prestador)
);

-- Relación N:M "incluye"
CREATE TABLE paquete_componente (
    id_paquete    NUMBER(10) NOT NULL,
    id_componente NUMBER(10) NOT NULL,
    CONSTRAINT pk_paquete_componente PRIMARY KEY (id_paquete, id_componente),
    CONSTRAINT fk_pc_paquete         FOREIGN KEY (id_paquete)    REFERENCES paquete (id_paquete) ON DELETE CASCADE,
    CONSTRAINT fk_pc_componente      FOREIGN KEY (id_componente) REFERENCES componente (id_componente)
);

CREATE TABLE salida (
    id_salida    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    fecha_inicio DATE         NOT NULL,
    cupo_maximo  NUMBER(2)    NOT NULL,
    estado       VARCHAR2(12) DEFAULT 'programada' NOT NULL,
    id_paquete   NUMBER(10)   NOT NULL,
    CONSTRAINT pk_salida         PRIMARY KEY (id_salida),
    CONSTRAINT ck_salida_cupo    CHECK (cupo_maximo BETWEEN 1 AND 60),
    CONSTRAINT ck_salida_estado  CHECK (estado IN ('programada', 'confirmada', 'cancelada', 'realizada')),
    CONSTRAINT fk_salida_paquete FOREIGN KEY (id_paquete) REFERENCES paquete (id_paquete)
);


-- ---------------------------------------------------------------------
-- Clientes y pasajeros
-- ---------------------------------------------------------------------

CREATE TABLE cliente (
    id_cliente       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombres          VARCHAR2(60)  NOT NULL,
    apellidos        VARCHAR2(60)  NOT NULL,
    tipo_documento   VARCHAR2(10)  NOT NULL,
    numero_documento VARCHAR2(15)  NOT NULL,
    correo           VARCHAR2(100) NOT NULL,
    telefono         VARCHAR2(10)  NOT NULL,
    fecha_nacimiento DATE          NOT NULL,
    ciudad_origen    VARCHAR2(60)  NOT NULL,
    CONSTRAINT pk_cliente            PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_documento  UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uq_cliente_correo     UNIQUE (correo),
    CONSTRAINT ck_cliente_tipo_doc   CHECK (tipo_documento IN ('CC', 'CE', 'pasaporte', 'TI')),
    CONSTRAINT ck_cliente_num_doc    CHECK (REGEXP_LIKE(numero_documento, '^[A-Za-z0-9]{5,15}$')),
    CONSTRAINT ck_cliente_correo     CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
    CONSTRAINT ck_cliente_telefono   CHECK (REGEXP_LIKE(telefono, '^3[0-9]{9}$')),
    CONSTRAINT ck_cliente_nacimiento CHECK (fecha_nacimiento >= DATE '1900-01-01')  -- "no futura": trigger
);

-- Cuenta del cliente (decisión 1): solo existe si el cliente se registró
CREATE TABLE perfil_cliente (
    id_perfil          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    contrasena_cifrada VARCHAR2(60) NOT NULL,
    idioma             VARCHAR2(10) DEFAULT 'espanol' NOT NULL,
    canal_preferido    VARCHAR2(10) DEFAULT 'correo'  NOT NULL,
    dias_anticipacion  NUMBER(1)    DEFAULT 3         NOT NULL,
    acepta_promociones VARCHAR2(2)  DEFAULT 'no'      NOT NULL,
    id_cliente         NUMBER(10)   NOT NULL,
    CONSTRAINT pk_perfil_cliente    PRIMARY KEY (id_perfil),
    CONSTRAINT uq_perfil_cliente    UNIQUE (id_cliente),                    -- 1:1 tiene_perfil
    CONSTRAINT ck_perfil_contrasena CHECK (LENGTH(contrasena_cifrada) = 60),
    CONSTRAINT ck_perfil_idioma     CHECK (idioma IN ('espanol', 'ingles')),
    CONSTRAINT ck_perfil_canal      CHECK (canal_preferido IN ('correo', 'sms', 'whatsapp')),
    CONSTRAINT ck_perfil_dias       CHECK (dias_anticipacion IN (1, 3, 7)),
    CONSTRAINT ck_perfil_promos     CHECK (acepta_promociones IN ('si', 'no')),
    CONSTRAINT fk_perfil_cliente    FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente) ON DELETE CASCADE
);

CREATE TABLE pasajero (
    id_pasajero      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombres          VARCHAR2(60) NOT NULL,
    apellidos        VARCHAR2(60) NOT NULL,
    tipo_documento   VARCHAR2(10) NOT NULL,
    numero_documento VARCHAR2(15) NOT NULL,
    fecha_nacimiento DATE         NOT NULL,
    CONSTRAINT pk_pasajero            PRIMARY KEY (id_pasajero),
    CONSTRAINT uq_pasajero_documento  UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT ck_pasajero_tipo_doc   CHECK (tipo_documento IN ('RC', 'TI', 'CC', 'CE', 'pasaporte')),
    CONSTRAINT ck_pasajero_num_doc    CHECK (REGEXP_LIKE(numero_documento, '^[A-Za-z0-9]{5,15}$')),
    CONSTRAINT ck_pasajero_nacimiento CHECK (fecha_nacimiento >= DATE '1900-01-01')
);


-- ---------------------------------------------------------------------
-- Cotizaciones
-- ---------------------------------------------------------------------

CREATE TABLE cotizacion (
    id_cotizacion     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    numero_cotizacion CHAR(10)     NOT NULL,
    fecha             DATE         NOT NULL,
    valor_total       NUMBER(12)   NOT NULL,
    estado            VARCHAR2(10) DEFAULT 'borrador' NOT NULL,
    id_prestador      NUMBER(10)   NOT NULL,     -- agencia que la emite ("cotiza")
    id_cliente        NUMBER(10)   NOT NULL,     -- cliente que la pide ("solicita")
    CONSTRAINT pk_cotizacion           PRIMARY KEY (id_cotizacion),
    CONSTRAINT uq_cotizacion_numero    UNIQUE (numero_cotizacion),
    CONSTRAINT ck_cotizacion_numero    CHECK (REGEXP_LIKE(numero_cotizacion, '^COT-[0-9]{6}$')),
    CONSTRAINT ck_cotizacion_valor     CHECK (valor_total > 0),
    CONSTRAINT ck_cotizacion_estado    CHECK (estado IN ('borrador', 'enviada', 'aceptada', 'rechazada', 'vencida')),
    CONSTRAINT fk_cotizacion_prestador FOREIGN KEY (id_prestador) REFERENCES prestador (id_prestador),
    CONSTRAINT fk_cotizacion_cliente   FOREIGN KEY (id_cliente)   REFERENCES cliente (id_cliente)
);

-- Entidad débil de COTIZACION (relación identificadora "contiene")
CREATE TABLE detalle_cotizacion (
    id_cotizacion     NUMBER(10) NOT NULL,
    numero_linea      NUMBER(3)  NOT NULL,
    fecha_servicio    DATE       NOT NULL,      -- > fecha de la cotización (RN25, trigger)
    cantidad_personas NUMBER(2)  NOT NULL,
    valor             NUMBER(12) NOT NULL,
    id_componente     NUMBER(10) NOT NULL,
    CONSTRAINT pk_detalle_cotizacion PRIMARY KEY (id_cotizacion, numero_linea),
    CONSTRAINT ck_detalle_linea      CHECK (numero_linea >= 1),
    CONSTRAINT ck_detalle_personas   CHECK (cantidad_personas BETWEEN 1 AND 20),
    CONSTRAINT ck_detalle_valor      CHECK (valor > 0),
    CONSTRAINT fk_detalle_cotizacion FOREIGN KEY (id_cotizacion) REFERENCES cotizacion (id_cotizacion) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_componente FOREIGN KEY (id_componente) REFERENCES componente (id_componente)
);


-- ---------------------------------------------------------------------
-- Reservas y pagos
-- ---------------------------------------------------------------------

CREATE TABLE reserva (
    id_reserva     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    fecha_creacion DATE         DEFAULT SYSDATE NOT NULL,
    valor_total    NUMBER(12)   NOT NULL,       -- valor acordado al reservar (no se recalcula)
    estado         VARCHAR2(10) DEFAULT 'pendiente' NOT NULL,
    canal          VARCHAR2(25) NOT NULL,
    id_plan        NUMBER(10)   NOT NULL,
    id_salida      NUMBER(10)   NOT NULL,       -- plan y salida del mismo paquete (RN14, trigger)
    id_cliente     NUMBER(10)   NOT NULL,
    id_cotizacion  NUMBER(10),                  -- solo si la reserva nació de una cotización
    fecha_cancelacion DATE,                     -- solo si se canceló (procedimiento cancelar_reserva)
    valor_reembolso   NUMBER(12),               -- 80 % de lo pagado si se canceló con más de 5 días (RN31)
    CONSTRAINT pk_reserva            PRIMARY KEY (id_reserva),
    CONSTRAINT uq_reserva_cotizacion UNIQUE (id_cotizacion),                -- 1:1 se_convierte
    CONSTRAINT ck_reserva_valor      CHECK (valor_total > 0 AND valor_total <= 1000000000),
    CONSTRAINT ck_reserva_estado     CHECK (estado IN ('pendiente', 'confirmada', 'cancelada', 'completada')),
    CONSTRAINT ck_reserva_canal      CHECK (canal IN ('web', 'aplicacion movil', 'telefono', 'mostrador', 'agencia intermediaria')),
    CONSTRAINT ck_reserva_reembolso  CHECK (valor_reembolso IS NULL OR (valor_reembolso >= 0 AND valor_reembolso <= valor_total)),
    CONSTRAINT ck_reserva_cancelacion CHECK (estado = 'cancelada' OR (fecha_cancelacion IS NULL AND valor_reembolso IS NULL)),
    CONSTRAINT fk_reserva_plan       FOREIGN KEY (id_plan)       REFERENCES plan (id_plan),
    CONSTRAINT fk_reserva_salida     FOREIGN KEY (id_salida)     REFERENCES salida (id_salida),
    CONSTRAINT fk_reserva_cliente    FOREIGN KEY (id_cliente)    REFERENCES cliente (id_cliente),
    CONSTRAINT fk_reserva_cotizacion FOREIGN KEY (id_cotizacion) REFERENCES cotizacion (id_cotizacion)
);

-- Relación N:M "viaja_en"
CREATE TABLE reserva_pasajero (
    id_reserva  NUMBER(10) NOT NULL,
    id_pasajero NUMBER(10) NOT NULL,
    CONSTRAINT pk_reserva_pasajero PRIMARY KEY (id_reserva, id_pasajero),
    CONSTRAINT fk_rp_reserva       FOREIGN KEY (id_reserva)  REFERENCES reserva (id_reserva) ON DELETE CASCADE,
    CONSTRAINT fk_rp_pasajero      FOREIGN KEY (id_pasajero) REFERENCES pasajero (id_pasajero)
);

-- Supertipo de la jerarquía PAGO -> PAGO_EN_LINEA
CREATE TABLE pago (
    id_pago     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    fecha_pago  DATE         DEFAULT SYSDATE NOT NULL,
    monto       NUMBER(12)   NOT NULL,
    metodo_pago VARCHAR2(20) NOT NULL,
    estado_pago VARCHAR2(12) DEFAULT 'pendiente' NOT NULL,
    id_reserva  NUMBER(10)   NOT NULL,
    CONSTRAINT pk_pago         PRIMARY KEY (id_pago),
    CONSTRAINT ck_pago_monto   CHECK (monto > 0),
    CONSTRAINT ck_pago_metodo  CHECK (metodo_pago IN ('tarjeta de credito', 'tarjeta debito', 'pse', 'transferencia', 'efectivo')),
    CONSTRAINT ck_pago_estado  CHECK (estado_pago IN ('exitoso', 'fallido', 'pendiente', 'reembolsado')),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva)
);

-- Subtipo: solo pagos con tarjeta o PSE (RN22, trigger)
CREATE TABLE pago_en_linea (
    id_pago                NUMBER(10)   NOT NULL,
    referencia_transaccion VARCHAR2(40) NOT NULL,
    CONSTRAINT pk_pago_en_linea      PRIMARY KEY (id_pago),
    CONSTRAINT uq_pago_en_linea_ref  UNIQUE (referencia_transaccion),
    CONSTRAINT ck_pago_en_linea_ref  CHECK (REGEXP_LIKE(referencia_transaccion, '^[A-Za-z0-9-]{1,40}$')),
    CONSTRAINT fk_pago_en_linea_pago FOREIGN KEY (id_pago) REFERENCES pago (id_pago) ON DELETE CASCADE
);


-- ---------------------------------------------------------------------
-- Notificaciones
-- ---------------------------------------------------------------------

CREATE TABLE notificacion (
    id_notificacion  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    tipo             VARCHAR2(25)  NOT NULL,
    canal            VARCHAR2(10)  NOT NULL,
    mensaje          VARCHAR2(500) NOT NULL,
    fecha_programada TIMESTAMP     NOT NULL,
    fecha_envio      TIMESTAMP,                 -- vacía mientras no se envía
    estado           VARCHAR2(10)  DEFAULT 'pendiente' NOT NULL,
    id_cliente       NUMBER(10)    NOT NULL,
    id_reserva       NUMBER(10),                -- vacía en promociones
    CONSTRAINT pk_notificacion         PRIMARY KEY (id_notificacion),
    CONSTRAINT ck_notificacion_tipo    CHECK (tipo IN ('recordatorio de reserva', 'confirmacion de reserva',
                                                       'confirmacion de pago', 'cambio de estado', 'promocion')),
    CONSTRAINT ck_notificacion_canal   CHECK (canal IN ('correo', 'sms', 'whatsapp')),
    CONSTRAINT ck_notificacion_estado  CHECK (estado IN ('pendiente', 'enviada', 'fallida', 'leida')),
    CONSTRAINT ck_notificacion_envio   CHECK (fecha_envio IS NULL OR fecha_envio >= fecha_programada),
    CONSTRAINT fk_notificacion_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente) ON DELETE CASCADE,
    CONSTRAINT fk_notificacion_reserva FOREIGN KEY (id_reserva) REFERENCES reserva (id_reserva) ON DELETE SET NULL
);


-- ---------------------------------------------------------------------
