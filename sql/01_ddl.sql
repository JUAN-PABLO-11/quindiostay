CREATE INDEX ix_paquete_destino     ON paquete (id_destino);
CREATE INDEX ix_paquete_prestador   ON paquete (id_prestador);
CREATE INDEX ix_componente_prest    ON componente (id_prestador);
CREATE INDEX ix_pc_componente       ON paquete_componente (id_componente);
CREATE INDEX ix_salida_paquete      ON salida (id_paquete);
CREATE INDEX ix_reserva_salida      ON reserva (id_salida);
CREATE INDEX ix_reserva_plan        ON reserva (id_plan);
CREATE INDEX ix_reserva_cliente     ON reserva (id_cliente);
CREATE INDEX ix_rp_pasajero         ON reserva_pasajero (id_pasajero);
CREATE INDEX ix_pago_reserva        ON pago (id_reserva);
CREATE INDEX ix_cotizacion_cliente  ON cotizacion (id_cliente);
CREATE INDEX ix_notificacion_client ON notificacion (id_cliente);
CREATE INDEX ix_notificacion_reserv ON notificacion (id_reserva);

